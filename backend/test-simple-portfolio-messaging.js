#!/usr/bin/env node

/**
 * Simple Portfolio Messaging Test
 * Quick test to validate the portfolio context in investment decisions
 */

const axios = require('axios');

const BASE_URL = 'http://localhost:3001/api';
const TEST_USER = {
  email: 'admin@realestateanalyzer.com', 
  password: 'Spring@2025'
};

let authToken = null;

async function authenticate() {
  try {
    const response = await axios.post(`${BASE_URL}/auth/login`, TEST_USER);
    authToken = response.data.accessToken;
    return true;
  } catch (error) {
    console.error('❌ Authentication failed:', error.response?.data || error.message);
    return false;
  }
}

async function testNegativeCashFlowMessaging() {
  console.log('🧪 Testing Negative Cash Flow Property Messaging...');
  
  // Property that should have negative cash flow
  const negativeFlowProperty = {
    propertyType: 'SFR',
    propertyName: 'Test Negative Cash Flow',
    propertyAddress: {
      street: '1105 Princeton Ave',
      city: 'Nashville', 
      state: 'TN',
      zipCode: '37203'
    },
    portfolioId: '68a7cef03b389ec982b013ff', // Correct portfolio ID for Princeton property
    purchasePrice: 400000,
    downPayment: 80000,
    interestRate: 7.5,
    loanTerm: 30,
    monthlyRent: 2200, // Too low for the price
    propertyTaxRate: 1.5,
    insuranceRate: 0.8,
    maintenanceCost: 500,
    propertyManagementRate: 10,
    yearBuilt: 2015,
    squareFootage: 2000,
    bedrooms: 3,
    bathrooms: 2,
    longTermAssumptions: {
      projectionYears: 10,
      annualRentIncrease: 2,
      annualPropertyValueIncrease: 3,
      sellingCostsPercentage: 6,
      vacancyRate: 5
    }
  };
  
  try {
    const analysis = await axios.post(`${BASE_URL}/deals/analyze`, negativeFlowProperty, {
      headers: { Authorization: `Bearer ${authToken}` }
    });
    
    const result = analysis.data;
    const cashFlow = result.monthlyAnalysis?.cashFlow || 0;
    
    console.log('📊 Analysis Results:');
    console.log(`Monthly Cash Flow: $${Math.round(cashFlow)}`);
    console.log(`Investment Decision exists: ${!!result.investmentDecision}`);
    console.log(`Portfolio Context exists: ${!!result.investmentDecision?.portfolioContext}`);
    
    if (result.investmentDecision?.portfolioContext) {
      const context = result.investmentDecision.portfolioContext;
      console.log('\n📋 Portfolio Context:');
      console.log(`Portfolio Name: ${context.portfolioName}`);
      console.log(`Portfolio Goal: ${context.portfolioGoal}`);
      console.log(`Fit Analysis: ${context.fitAnalysis}`);
      console.log(`Impact Summary: ${context.impactSummary}`);
      
      // Check for the bug
      if (cashFlow < 0 && context.impactSummary?.includes('positive monthly returns')) {
        console.log('\n🚨 BUG DETECTED: Negative cash flow property showing positive messaging!');
        return false;
      }
    } else {
      console.log('\n⚠️  No portfolio context found in investment decision');
      console.log('This suggests portfolio context is not being generated by backend');
    }
    
    return true;
    
  } catch (error) {
    console.error('❌ Test failed:', error.response?.data || error.message);
    return false;
  }
}

async function main() {
  if (!await authenticate()) {
    process.exit(1);
  }
  
  const success = await testNegativeCashFlowMessaging();
  process.exit(success ? 0 : 1);
}

if (require.main === module) {
  main();
}